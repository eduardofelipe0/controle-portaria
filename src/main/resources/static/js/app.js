(() => {
  'use strict';
  document.querySelectorAll('[data-password-toggle]').forEach((button) => {
    const input = document.getElementById(button.dataset.passwordToggle);
    if (!input) return;
    button.addEventListener('click', () => {
      const show = input.type === 'password';
      input.type = show ? 'text' : 'password';
      button.setAttribute('aria-label', show ? 'Ocultar senha' : 'Mostrar senha');
      button.setAttribute('aria-pressed', String(show));
      const icon = button.querySelector('img');
      if (icon) icon.src = icon.src.replace(/eye(?:-slash)?\.svg(?:\?.*)?$/, show ? 'eye-slash.svg' : 'eye.svg');
    });
  });
  document.querySelectorAll('form[data-confirm]').forEach((form) => {
    form.addEventListener('submit', (event) => {
      if (!window.confirm(form.dataset.confirm)) event.preventDefault();
    });
  });
  const sidebarToggle = document.getElementById('sidebarToggle');
  const backdrop = document.getElementById('sidebarBackdrop');
  const body = document.body;
  const isMobile = () => window.matchMedia('(max-width: 1024px)').matches;
  function closeSidebar() {
    body.classList.remove('sidebar-open');
    sidebarToggle?.setAttribute('aria-expanded', 'false');
  }
  sidebarToggle?.addEventListener('click', () => {
    if (isMobile()) {
      body.classList.toggle('sidebar-open');
      sidebarToggle.setAttribute('aria-expanded', String(body.classList.contains('sidebar-open')));
    } else {
      body.classList.toggle('sidebar-collapsed');
    }
  });
  backdrop?.addEventListener('click', closeSidebar);
  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') closeSidebar();
  });
  document.querySelectorAll('.side-link').forEach((link) => {
    try {
      const target = new URL(link.href, window.location.href).pathname;
      const path = window.location.pathname;
      if (path === target || (target.endsWith('/listar') && path.startsWith(target.slice(0, -6)))) {
        link.classList.add('active');
        link.setAttribute('aria-current', 'page');
      }
    } catch (_) { /* URLs generated by the server are trusted. */ }
  });
})();
